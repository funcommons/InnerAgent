    payload_json            TEXT         NOT NULL,
    event_created_at        TIMESTAMP(3),
    redis_published_at      TIMESTAMP(3),
    publish_required        BOOLEAN      NOT NULL,
    publish_status          VARCHAR(16)  NOT NULL,
    publish_claim_owner     VARCHAR(128),
    publish_claim_until     TIMESTAMP(3),
    next_publish_attempt_at TIMESTAMP(3),
    last_publish_error      VARCHAR(1024),
    publish_attempts        INT          NOT NULL DEFAULT 0,
    create_time             TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ia_agent_event_sequence UNIQUE (run_id, sequence_no),
    CONSTRAINT chk_ia_agent_event_publish_state CHECK (
        (publish_required = FALSE AND publish_status = 'NOT_REQUIRED')
        OR (publish_required = TRUE
            AND publish_status IN ('PENDING', 'CLAIMED', 'PUBLISHED'))),
    CONSTRAINT chk_ia_agent_event_publish_attempts CHECK (publish_attempts >= 0),
    CONSTRAINT chk_ia_agent_event_sequence CHECK (sequence_no >= 1),
    CONSTRAINT chk_ia_agent_event_schema_version CHECK (schema_version >= 1)
);

CREATE INDEX idx_ia_agent_event_projection
