-- ---------------------------------------------------------------------
-- 1. ia_app:应用注册表(新增;单应用部署预置 default 应用 id=1)
-- ---------------------------------------------------------------------
CREATE TABLE ia_app (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_key                     VARCHAR(64)  NOT NULL,
    name                        VARCHAR(128) NOT NULL,
    sign_public_key             TEXT,
