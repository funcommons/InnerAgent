-- ---------------------------------------------------------------------
-- 3. ia_tool_grant:用户工具授权表(新增;会话级/永久授权)
-- ---------------------------------------------------------------------
CREATE TABLE ia_tool_grant (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id         BIGINT       NOT NULL DEFAULT 1,
    tenant_id      BIGINT       NOT NULL DEFAULT 0,
    user_id        BIGINT       NOT NULL,
    tool_fqn       VARCHAR(200) NOT NULL,
    scope          VARCHAR(16)  NOT NULL,
    conversation_id BIGINT,
    risk_at_grant  VARCHAR(16),
    schema_sha256  CHAR(64),
    source         VARCHAR(16),
    deleted        BOOLEAN      NOT NULL DEFAULT FALSE,
    create_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- conversation_id 在永久授权(scope=permanent)时为 NULL,
    -- NULLS NOT DISTINCT 保证同一用户对同一工具的永久授权唯一
    CONSTRAINT uk_ia_tool_grant UNIQUE NULLS NOT DISTINCT
        (app_id, user_id, tool_fqn, scope, conversation_id)
);

COMMENT ON TABLE ia_tool_grant IS '用户工具授权表(会话级/永久;风险升级或 schema 变更自动失效)';
COMMENT ON COLUMN ia_tool_grant.id IS '主键ID';
COMMENT ON COLUMN ia_tool_grant.app_id IS '所属应用;单应用部署固定为 1,P1 接入 AppContext 后显式写入';
COMMENT ON COLUMN ia_tool_grant.tenant_id IS '所属租户(团队)ID';
COMMENT ON COLUMN ia_tool_grant.user_id IS '被授权用户ID';
COMMENT ON COLUMN ia_tool_grant.tool_fqn IS '工具全限定名(ia_tool_registry.fqn)';
COMMENT ON COLUMN ia_tool_grant.scope IS '授权作用域:conversation-仅本会话 permanent-永久';
COMMENT ON COLUMN ia_tool_grant.conversation_id IS '会话ID(ia_agent_conversation.id;scope=permanent 时为 NULL)';
COMMENT ON COLUMN ia_tool_grant.risk_at_grant IS '授予时工具风险等级快照';
COMMENT ON COLUMN ia_tool_grant.schema_sha256 IS '授予时工具清单 SHA-256 快照(变更检测)';
COMMENT ON COLUMN ia_tool_grant.source IS '授权来源:live-confirm(确认流)/admin 等';
COMMENT ON COLUMN ia_tool_grant.deleted IS '逻辑删除标志(撤销授权)';
