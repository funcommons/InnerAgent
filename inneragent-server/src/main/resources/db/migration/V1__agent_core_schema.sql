-- =====================================================================
-- InnerAgent V1:Agent 核心表(Agent 定义/对话/消息/运行/事件/模型调用量)
-- 移植自融光 ai-fusion-video 迁移(参考源,列定义逐一对照):
--   * B1.1.0.0.8__baseline_1.0.0.sql(afv_agent_conversation / afv_agent_message)
--   * V1.0.4.0.1__expand_script_and_agent_message_text_columns.sql(message.content 扩容)
--   * V1.0.6.1.5__agent_run_and_event.sql(afv_agent_run / afv_agent_event / afv_agent_model_call_usage)
--   * V1.1.0.0.8__agent_state_retention.sql(conversation 状态保留列与索引)
-- 改造规则(见 02-技术方案 §5.1):
--   * MySQL 8 -> PostgreSQL 17 方言;afv_ 前缀 -> ia_ 前缀。
--   * 所有业务表增加 app_id BIGINT NOT NULL DEFAULT 1(所属应用;单应用部署固定为 1,
--     P1 接入 AppContext 后显式写入)。
--   * 公共列对齐实体基类:实体继承 TenantBaseEntity 的表保留 tenant_id;deleted 用 BOOLEAN。
--   * ia_agent_event.schema_version:事件载荷结构版本(持久事件版本化,fail-fast 兼容策略)。
--   * MySQL AUTO_INCREMENT -> GENERATED BY DEFAULT AS IDENTITY;DATETIME -> TIMESTAMP;
--     MEDIUMTEXT/LONGTEXT -> TEXT(TOAST 无 16MB 上限)。
--   * PostgreSQL 无 ON UPDATE CURRENT_TIMESTAMP:update_time 由应用层
--     (MyBatis-Plus FieldFill.INSERT_UPDATE / 运行时 SQL 显式赋值)维护。
--   * 索引按融光原样保留(改名换前缀);补充应用维度查询索引
--     idx_ia_conv_app_user_time(融光注释中的 updated_at 对应本表 update_time);
--     ia_agent_event(run_id, sequence_no) 查询已由唯一约束 uk_ia_agent_event_sequence
--     前缀覆盖,不重复建索引。
-- =====================================================================

