    lease_until                    TIMESTAMP(3),
    next_sequence                  BIGINT      NOT NULL DEFAULT 1,
    terminal_sequence              BIGINT,
    terminal_output_type           VARCHAR(32),
    cancel_requested_at            TIMESTAMP(3),
    cancel_broadcast_at            TIMESTAMP(3),
    cancel_acknowledged_at         TIMESTAMP(3),
    cancel_next_attempt_at         TIMESTAMP(3),
    waiting_reply_id               VARCHAR(128),
    waiting_tool_call_id           VARCHAR(128),
    waiting_tool_name              VARCHAR(128),
    wait_expires_at                TIMESTAMP(3),
    paused_through_sequence        BIGINT,
    deadline_at                    TIMESTAMP(3) NOT NULL,
    started_at                     TIMESTAMP(3) NOT NULL,
    heartbeat_at                   TIMESTAMP(3),
    finished_at                    TIMESTAMP(3),
    error_code                     VARCHAR(64),
    error_message                  TEXT,
    usage_settled                  BOOLEAN     NOT NULL DEFAULT FALSE,
    usage_settled_at               TIMESTAMP(3),
    projected_through_sequence     BIGINT      NOT NULL DEFAULT 0,
    projection_completed_at        TIMESTAMP(3),
    active_conversation_id         VARCHAR(64) GENERATED ALWAYS AS (
        CASE
            WHEN parent_run_id IS NULL
                 AND status IN (
                     'RUNNING',
                     'WAITING_CONFIRMATION',
                     'WAITING_EXTERNAL',
                     'CANCEL_REQUESTED')
            THEN conversation_id
        END
    ) STORED,
    create_time                    TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time                    TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ia_agent_run_id UNIQUE (run_id),
    CONSTRAINT uk_ia_agent_run_active UNIQUE (active_conversation_id),
    CONSTRAINT uk_ia_agent_run_parent_tool UNIQUE (parent_run_id, parent_tool_call_id),
    CONSTRAINT chk_ia_agent_run_parent_identity CHECK (
        (parent_run_id IS NULL AND parent_tool_call_id IS NULL)
        OR (parent_run_id IS NOT NULL
            AND parent_tool_call_id IS NOT NULL
            AND agent_name IS NOT NULL)),
    CONSTRAINT chk_ia_agent_run_status CHECK (
        status IN (
            'RUNNING',
            'WAITING_CONFIRMATION',
            'WAITING_EXTERNAL',
            'CANCEL_REQUESTED',
            'COMPLETED',
            'FAILED',
            'CANCELLED')),
    CONSTRAINT chk_ia_agent_run_usage_settled CHECK (usage_settled IN (FALSE, TRUE))
);

CREATE INDEX idx_ia_agent_run_conversation_status
    ON ia_agent_run (conversation_id, status, id);
CREATE INDEX idx_ia_agent_run_parent_status
    ON ia_agent_run (parent_run_id, status, id);
