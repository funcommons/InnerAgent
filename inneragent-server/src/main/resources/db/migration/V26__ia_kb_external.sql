-- =====================================================================
-- InnerAgent V26(序号让位:V25 由并行批次 D2 占用):外部知识库登记
-- (契约源 docs/使用手册/03-接入指南/06-外部知识库API规范.md)。平台发起
-- 检索、宿主返回命中;与内置 mini KB 并存 RRF 融合;外接源失败 = 零命中
-- 不阻断会话。应用级登记(每应用暂限 1);credentials 只存管理面不回显。
-- 唯一性:appId+name 活跃行唯一(部分唯一索引带 deleted 谓词,V13 先例),
-- 软删后可重新登记。教训落档(DEF-08/V24):无 JSONB;携带 app_id+tenant_id
-- 双行级列(tenant_id 实体不映射,注入由行级拦截器负责)。
-- =====================================================================

CREATE TABLE ia_kb_external (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id       BIGINT        NOT NULL DEFAULT 1,
    tenant_id    BIGINT        NOT NULL DEFAULT 0,
    name         VARCHAR(128)  NOT NULL,
    endpoint_url VARCHAR(2048) NOT NULL,
    auth_type    VARCHAR(32)   NOT NULL DEFAULT 'NONE',
    header_name  VARCHAR(128),
    credentials  TEXT,
    status       VARCHAR(16)   NOT NULL DEFAULT 'active',
    timeout_ms   INT           NOT NULL DEFAULT 10000,
    deleted      BOOLEAN       NOT NULL DEFAULT FALSE,
    create_time  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_ia_kb_external_auth CHECK (auth_type IN ('NONE', 'STATIC_HEADER')),
    CONSTRAINT chk_ia_kb_external_status CHECK (status IN ('active', 'inactive'))
);

COMMENT ON TABLE ia_kb_external IS '外部知识库登记(平台发起检索、宿主返回命中;每应用暂限 1 个,失败按零命中不阻断会话)';
COMMENT ON COLUMN ia_kb_external.app_id IS '所属应用;单应用部署固定为 1(行级拦截器注入)';
COMMENT ON COLUMN ia_kb_external.tenant_id IS '所属租户(团队)ID(行级拦截器落值;V24 全库缺列灭族同款)';
COMMENT ON COLUMN ia_kb_external.name IS '展示名(appId+name 活跃行唯一)';
COMMENT ON COLUMN ia_kb_external.endpoint_url IS '宿主检索端点(POST)';
COMMENT ON COLUMN ia_kb_external.auth_type IS '鉴权策略:NONE / STATIC_HEADER(静态头)';
COMMENT ON COLUMN ia_kb_external.header_name IS '静态头名(auth_type=STATIC_HEADER 时成对必填)';
COMMENT ON COLUMN ia_kb_external.credentials IS '静态头值/凭据(TEXT;只存管理面,不回显、不进审计/日志;加密存储可延后)';
COMMENT ON COLUMN ia_kb_external.status IS '状态:active-参与检索/inactive-失效';
COMMENT ON COLUMN ia_kb_external.timeout_ms IS '单次检索超时(毫秒,§3 默认 10s;不重试)';
COMMENT ON COLUMN ia_kb_external.deleted IS '逻辑删除标志(活跃行不占唯一键,软删后可重新登记)';

CREATE UNIQUE INDEX uk_ia_kb_external_active_name
    ON ia_kb_external (app_id, name)
    WHERE deleted = FALSE;

CREATE INDEX idx_ia_kb_external_app
    ON ia_kb_external (app_id, status)
    WHERE deleted = FALSE;
